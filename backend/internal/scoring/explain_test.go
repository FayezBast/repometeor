func TestExplainAccelerationBoundary(t *testing.T) {
	// A ratio just below 1.5 must not be reported; just above must be.
	build := func(secondHalfGain int) Input {
		// First half: 30 stars over 3h → 10/h.
		return baseInput(hourly(refTime, 100, 110, 120, 130,
			130+secondHalfGain/3, 130+2*secondHalfGain/3, 130+secondHalfGain))
	}

	below := explainFor(build(42), Window6h) // 14/h → ratio 1.4
	if slices.Contains(codesOf(below), CodeAccelerating) {
		t.Errorf("a ratio of 1.4 should not be reported as accelerating; got %v", codesOf(below))
	}

	above := explainFor(build(48), Window6h) // 16/h → ratio 1.6
	if !slices.Contains(codesOf(above), CodeAccelerating) {
		t.Errorf("a ratio of 1.6 should be reported as accelerating; got %v", codesOf(above))
	}
}

