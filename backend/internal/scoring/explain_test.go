func explainFor(in Input, w Window) []Explanation {
	opts := DefaultOptions()
	f := ComputeFeatures(refTime, w, in, opts)
	eligibility, _ := Classify(f, w, in, opts)
	return Explain(refTime, w, f, in, eligibility)
}

func codesOf(explanations []Explanation) []string {
	out := make([]string, 0, len(explanations))
	for _, e := range explanations {
		out = append(out, e.Code)
	}
	return out
}

func textFor(explanations []Explanation, code string) (string, bool) {
	for _, e := range explanations {
		if e.Code == code {
			return e.Text, true
		}
	}
	return "", false
}

