func TestExplainCapsAtThreeReasons(t *testing.T) {
	// Construct a repository that qualifies for many reasons at once.
	snapshots := hourly(refTime, 100, 105, 110, 115, 160, 220, 300)
	for i := range snapshots {
		snapshots[i].Forks = 10 + i*4
	}
	in := baseInput(snapshots)
	pushed := refTime.Add(-time.Hour)
	release := refTime.Add(-24 * time.Hour)
	in.PushedAt = &pushed
	in.LatestReleaseAt = &release

	got := explainFor(in, Window6h)
	if len(got) > MaxReasons {
		t.Fatalf("got %d explanations, want at most %d", len(got), MaxReasons)
	}
	if len(got) != MaxReasons {
		t.Fatalf("got %d explanations, want exactly %d for a repository qualifying on many counts", len(got), MaxReasons)
	}
}

func TestExplainOrderIsDeterministicAndFollowsPriority(t *testing.T) {
	snapshots := hourly(refTime, 100, 105, 110, 115, 160, 220, 300)
	for i := range snapshots {
		snapshots[i].Forks = 10 + i*4
	}
	in := baseInput(snapshots)

	first := codesOf(explainFor(in, Window6h))
	for range 10 {
		if got := codesOf(explainFor(in, Window6h)); !slices.Equal(got, first) {
			t.Fatalf("explanation order is not stable: %v then %v", first, got)
		}
	}

	// The emitted codes must appear in reasonPriority order.
	lastIndex := -1
	for _, code := range first {
		index := slices.Index(reasonPriority, code)
		if index < 0 {
			t.Fatalf("code %q is not in reasonPriority", code)
		}
		if index <= lastIndex {
			t.Fatalf("codes %v are not in priority order", first)
		}
		lastIndex = index
	}
}

func TestExplanationsEndWithAPeriod(t *testing.T) {
	cases := []Input{
		baseInput(hourly(refTime, 100, 110, 120, 130, 140, 150, 160)),
		baseInput(hourly(refTime, 100, 100, 100, 100, 100, 100, 100)),
		baseInput(hourly(refTime, 200, 190, 180, 170, 160, 150, 140)),
	}
	for _, in := range cases {
		for _, e := range explainFor(in, Window6h) {
			if !strings.HasSuffix(e.Text, ".") {
				t.Errorf("%q does not end with a period", e.Text)
			}
			if e.Text == "" || strings.ToUpper(e.Text[:1]) != e.Text[:1] {
				t.Errorf("%q does not start with a capital letter", e.Text)
			}
		}
	}
}

