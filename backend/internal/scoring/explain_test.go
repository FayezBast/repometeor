func TestExplanationsNeverAccuseRepositories(t *testing.T) {
	// The product must describe data, not allege wrongdoing. This guards the
	// wording of both the explanation strings and the anomaly flag identifiers.
	forbidden := []string{
		"fake", "bought", "buying", "purchase", "manipulat", "fraud",
		"cheat", "scam", "botted", "suspicious", "abuse",
	}

	var corpus []string
	corpus = append(corpus, reasonPriority...)
	corpus = append(corpus, FlagUnusualStarForkRatio, FlagStaleRepositorySpike,
		FlagInsufficientHistory, FlagLargeSingleInterval, FlagSnapshotGap, FlagRecentlyDiscovered)

	inputs := []Input{
		baseInput(hourly(refTime, 100, 110, 120, 130, 140, 150, 160)),
		baseInput(hourly(refTime, 100, 100, 100, 100, 100, 100, 100)),
		baseInput(hourly(refTime, 100, 105, 110, 115, 160, 220, 300)),
	}
	for _, in := range inputs {
		for _, e := range explainFor(in, Window6h) {
			corpus = append(corpus, e.Text)
		}
	}

	for _, text := range corpus {
		lower := strings.ToLower(text)
		for _, word := range forbidden {
			if strings.Contains(lower, word) {
				t.Errorf("%q contains the accusatory term %q", text, word)
			}
		}
	}
}
