func TestProvisionalEntriesAlwaysDisclaimTheirHistory(t *testing.T) {
	// Whatever else a New Entrant qualifies for, the caveat must survive the
	// three-reason cap.
	snapshots := hourly(refTime, 40, 60, 90, 130, 190, 260, 340)
	for i := range snapshots {
		snapshots[i].Forks = 2 + i*5
	}
	in := baseInput(snapshots)
	in.FirstSeenAt = refTime.Add(-6 * time.Hour)
	release := refTime.Add(-24 * time.Hour)
	in.LatestReleaseAt = &release

	opts := DefaultOptions()
	f := ComputeFeatures(refTime, Window24h, in, opts)
	eligibility, _ := Classify(f, Window24h, in, opts)
	if eligibility != EligibleProvisional {
		t.Fatalf("Eligibility = %q, want provisional", eligibility)
	}

	codes := codesOf(Explain(refTime, Window24h, f, in, eligibility))
	if !slices.Contains(codes, CodeLimitedHistory) {
		t.Fatalf("codes = %v, want %s to survive the cap", codes, CodeLimitedHistory)
	}
}

