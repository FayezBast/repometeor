func TestExplainForkGain(t *testing.T) {
	snapshots := hourly(refTime, 100, 110, 120, 130, 140, 150, 160)
	for i := range snapshots {
		snapshots[i].Forks = 10 + i*3 // 18 forks gained over the window
	}
	got := explainFor(baseInput(snapshots), Window6h)

	text, ok := textFor(got, CodeForkGain)
	if !ok {
		// Fork gain may be crowded out of the top three; check it is at least
		// generated by asking for it directly.
		opts := DefaultOptions()
		in := baseInput(snapshots)
		f := ComputeFeatures(refTime, Window6h, in, opts)
		if f.PositiveForkDelta != 18 {
			t.Fatalf("PositiveForkDelta = %d, want 18", f.PositiveForkDelta)
		}
		t.Skipf("fork_gain was crowded out by higher-priority reasons: %v", codesOf(got))
	}
	if !strings.Contains(text, "18 new forks") {
		t.Fatalf("text = %q, want it to mention 18 new forks", text)
	}
}

